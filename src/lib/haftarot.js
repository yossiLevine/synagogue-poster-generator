function numToHebrewGematria(num) {
  const n = parseInt(num, 10);
  if (isNaN(n) || n <= 0) return num;
  if (n === 15) return 'ט"ו';
  if (n === 16) return 'ט"ז';
  const tens = ['', 'י', 'כ', 'ל', 'מ', 'נ', 'ס', 'ע', 'פ', 'צ'];
  const units = ['', 'א', 'ב', 'ג', 'ד', 'ה', 'ו', 'ז', 'ח', 'ט'];
  const t = Math.floor(n / 10);
  const u = n % 10;
  let str = (tens[t] || '') + (units[u] || '');
  if (str.length === 1) return str + '\'';
  if (str.length > 1) return str.slice(0, -1) + '"' + str.slice(-1);
  return num;
}

export function translateRawHaftarah(raw) {
  if (!raw) return '';
  let clean = raw.split('|')[0].trim();
  for (const [en, he] of Object.entries(TANAKH_BOOKS)) {
    clean = clean.split(en).join(he);
  }
  return clean;
}

export function resolveHaftarah({ parasha = '', specialShabbat = '', rawHaftarah = '' } = {}) {
  // 1. Check special Shabbat first (e.g. Shabbat Shuva, Shabbat Zachor)
  if (specialShabbat && SPECIAL_HAFTAROT[specialShabbat]) {
    return SPECIAL_HAFTAROT[specialShabbat];
  }

  // 2. Check if rawHaftarah has Shabbat Shuva indication
  if (rawHaftarah && rawHaftarah.includes('Shabbat Shuva')) {
    return SPECIAL_HAFTAROT['שבת שובה'];
  }

  // 3. Clean parasha name
  const cleanParasha = (parasha || '')
    .replace(/^פרשת\s+/, '')
    .replace(/^Parashat\s+/i, '')
    .trim();

  // Special case: Ha'azinu in 5787 is Shabbat Shuva
  if (cleanParasha === 'האזינו' && specialShabbat?.includes('שובה')) {
    return SPECIAL_HAFTAROT['שבת שובה'];
  }

  // 4. Parasha lookup table
  if (cleanParasha && PARASHA_HAFTAROT[cleanParasha]) {
    return PARASHA_HAFTAROT[cleanParasha];
  }

  // Double parshiot lookup (e.g. מטות-מסעי, תזריע-מצורע, נצבים-וילך)
  if (cleanParasha.includes('-')) {
    const parts = cleanParasha.split('-');
    const secondPart = parts[1]?.trim();
    if (secondPart && PARASHA_HAFTAROT[secondPart]) {
      return PARASHA_HAFTAROT[secondPart];
    }
  }

  // 5. Fallback: translate raw Hebcal leyning.haftarah
  if (rawHaftarah) {
    return translateRawHaftarah(rawHaftarah);
  }

  return '';
}
