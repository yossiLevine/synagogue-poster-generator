/**
 * Returns a curated insight for a parasha or holiday.
 * @param {string} parashaName - Name of the parasha
 * @param {number} [index] - Optional specific index to pick
 * @returns {string} Inspirational thought
 */
export function getCuratedInsight(parashaName, index = null) {
  if (!parashaName) {
    return GENERAL_FALLBACKS[Math.floor(Math.random() * GENERAL_FALLBACKS.length)];
  }

  // Normalize parasha string (strip "פרשת ", trimming)
  const clean = parashaName.replace(/^פרשת\s+/, '').trim();
  
  // Look for exact or partial match
  let options = PARASHA_INSIGHTS[clean];
  
  if (!options) {
    for (const [key, list] of Object.entries(PARASHA_INSIGHTS)) {
      if (clean.includes(key) || key.includes(clean)) {
        options = list;
        break;
      }
    }
  }

  if (options && options.length > 0) {
    if (index !== null && index >= 0) {
      return options[index % options.length];
    }
    return options[Math.floor(Math.random() * options.length)];
  }

  return GENERAL_FALLBACKS[Math.floor(Math.random() * GENERAL_FALLBACKS.length)];
}
